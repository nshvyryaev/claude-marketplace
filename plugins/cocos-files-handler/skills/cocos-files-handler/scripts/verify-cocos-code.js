#!/usr/bin/env node
/**
 * verify-cocos-code.js
 *
 * Static checks for Cocos Creator 3.x TypeScript that the compiler does NOT catch.
 * Every rule here corresponds to a mistake that only surfaced at runtime or at build time.
 *
 * Usage:
 *   node verify-cocos-code.js --file assets/scripts/Foo.ts [--file ...]
 *   node verify-cocos-code.js --all              # scan assets/scripts recursively
 *   node verify-cocos-code.js --all --json       # machine-readable output
 *
 * Exit code: 0 when clean, 1 when at least one error-severity finding exists.
 *
 * Suppression: append `// cocos-verify-ignore` to the offending line.
 */

const fs = require('fs');
const path = require('path');

const ROOT_DIR = process.env.CLAUDE_PROJECT_DIR || process.cwd();
const IGNORE_MARKER = 'cocos-verify-ignore';

// ── Rules ────────────────────────────────────────────────────────────────────
// Each rule: { id, severity, test(line) -> bool, message }
// `test` runs per source line, after comment/ignore filtering.

const RULES = [
    {
        id: 'no-set-active',
        severity: 'error',
        // node.setActive(x) / node?.setActive(x) — the Cocos 2.x / Unity habit.
        test: (line) => /\.\s*setActive\s*\(/.test(line) || /\?\.\s*setActive\s*\(/.test(line),
        message:
            'cc.Node has no setActive() in Cocos Creator 3.x — it exists only in 2.x and Unity. ' +
            'TypeScript does not flag this; it throws "setActive is not a function" at runtime, ' +
            'and optional chaining (node?.setActive(...)) passes the null check and still throws. ' +
            'Use the property instead: `node.active = bool` (guard with `if (node)` when nullable).',
    },
    {
        id: 'no-json-import',
        severity: 'error',
        // import x from './foo.json'  |  import('./foo.json')
        test: (line) =>
            /\bimport\b[^;]*\bfrom\s*['"][^'"]+\.json['"]/.test(line) ||
            /\bimport\s*\(\s*['"][^'"]+\.json['"]\s*\)/.test(line),
        message:
            'The generated temp/tsconfig.cocos.json does not enable resolveJsonModule, so importing ' +
            'a .json file fails to compile. Either put the data in a TypeScript literal under ' +
            'assets/scripts/config/, or place the .json under assets/resources/ and load it at ' +
            'runtime via cc.resources.load(path, JsonAsset, cb).',
    },
];

// Rules that apply to the file path rather than its contents.
const FILE_RULES = [
    {
        id: 'no-generated-tsconfig-edit',
        severity: 'error',
        test: (relPath) => /(^|[/\\])temp[/\\]tsconfig\.cocos\.json$/.test(relPath),
        message:
            'temp/tsconfig.cocos.json is generated by Cocos Creator and is overwritten on the next ' +
            'refresh — edits to it are silently lost. Change the project tsconfig.json (which extends ' +
            'it) instead, or solve the problem without a compiler-option change.',
    },
];

// ── Scanning ─────────────────────────────────────────────────────────────────

/** Strip the tail of a line that is inside a // comment, so rules ignore commented-out code. */
function stripLineComment(line) {
    // Naive but adequate: ignore // that appears inside a string literal.
    let inSingle = false, inDouble = false, inTick = false;
    for (let i = 0; i < line.length - 1; i++) {
        const c = line[i];
        if (c === '\\') { i++; continue; }
        if (c === "'" && !inDouble && !inTick) inSingle = !inSingle;
        else if (c === '"' && !inSingle && !inTick) inDouble = !inDouble;
        else if (c === '`' && !inSingle && !inDouble) inTick = !inTick;
        else if (c === '/' && line[i + 1] === '/' && !inSingle && !inDouble && !inTick) {
            return line.slice(0, i);
        }
    }
    return line;
}

/**
 * Scan a source string. Returns an array of findings:
 *   { rule, severity, line, column: null, text, message }
 */
function scanSource(source, relPath = '') {
    const findings = [];

    for (const rule of FILE_RULES) {
        if (relPath && rule.test(relPath.replace(/\\/g, '/'))) {
            findings.push({ rule: rule.id, severity: rule.severity, line: 0, text: relPath, message: rule.message });
        }
    }

    // Content rules only make sense for TypeScript/JavaScript sources.
    if (relPath && !/\.(ts|js|mts|cts)$/i.test(relPath)) return findings;

    const lines = source.split(/\r?\n/);
    let inBlockComment = false;

    for (let i = 0; i < lines.length; i++) {
        const raw = lines[i];
        if (raw.includes(IGNORE_MARKER)) continue;

        // Track /* */ blocks so commented-out code does not trip the rules.
        let line = raw;
        if (inBlockComment) {
            const end = line.indexOf('*/');
            if (end === -1) continue;
            line = line.slice(end + 2);
            inBlockComment = false;
        }
        const open = line.lastIndexOf('/*');
        const close = line.lastIndexOf('*/');
        if (open !== -1 && open > close) {
            inBlockComment = true;
            line = line.slice(0, open);
        }

        line = stripLineComment(line);
        if (!line.trim()) continue;

        for (const rule of RULES) {
            if (rule.test(line)) {
                findings.push({
                    rule: rule.id,
                    severity: rule.severity,
                    line: i + 1,
                    text: raw.trim(),
                    message: rule.message,
                });
            }
        }
    }

    return findings;
}

/** Scan one file on disk. Missing files yield no findings (the caller may have deleted it). */
function scanFile(absPath) {
    if (!fs.existsSync(absPath) || !fs.statSync(absPath).isFile()) return [];
    const rel = path.relative(ROOT_DIR, absPath).replace(/\\/g, '/');
    let source = '';
    try { source = fs.readFileSync(absPath, 'utf8'); } catch { return []; }
    return scanSource(source, rel || path.basename(absPath)).map((f) => ({ ...f, file: rel || absPath }));
}

function collectAll(dir, out = []) {
    if (!fs.existsSync(dir)) return out;
    for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
        const p = path.join(dir, entry.name);
        if (entry.isDirectory()) collectAll(p, out);
        else if (/\.ts$/i.test(entry.name)) out.push(p);
    }
    return out;
}

// ── CLI ──────────────────────────────────────────────────────────────────────

function main() {
    const argv = process.argv.slice(2);
    const asJson = argv.includes('--json');
    const files = [];

    if (argv.includes('--all')) {
        files.push(...collectAll(path.join(ROOT_DIR, 'assets', 'scripts')));
    }
    for (let i = 0; i < argv.length; i++) {
        if (argv[i] === '--file') {
            const v = argv[i + 1];
            if (!v) { console.error('--file requires a path'); process.exit(2); }
            files.push(path.isAbsolute(v) ? v : path.join(ROOT_DIR, v));
            i++;
        }
    }

    if (files.length === 0) {
        console.error('Nothing to scan. Pass --file <path> (repeatable) or --all.');
        process.exit(2);
    }

    const findings = files.flatMap(scanFile);

    if (asJson) {
        process.stdout.write(JSON.stringify({ findings }, null, 2) + '\n');
    } else if (findings.length === 0) {
        console.log(`verify-cocos-code: ${files.length} file(s) scanned — clean.`);
    } else {
        for (const f of findings) {
            const loc = f.line ? `${f.file}:${f.line}` : f.file;
            console.log(`\n[${f.severity}] ${loc}  (${f.rule})`);
            if (f.line) console.log(`  ${f.text}`);
            console.log(`  → ${f.message}`);
        }
        console.log(`\n${findings.length} finding(s) in ${files.length} file(s).`);
    }

    process.exit(findings.some((f) => f.severity === 'error') ? 1 : 0);
}

module.exports = { scanSource, scanFile, RULES, FILE_RULES, IGNORE_MARKER };

if (require.main === module) main();
